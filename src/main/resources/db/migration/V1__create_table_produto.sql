CREATE TABLE PRODUTO (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(120 CHAR) NOT NULL,
    SKU VARCHAR2(60 CHAR) NOT NULL,
    PRECO NUMBER(15,2) NOT NULL,
    ATIVO NUMBER(1) DEFAULT 1 NOT NULL,
    CRIADO_EM TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_PRODUTO_SKU UNIQUE (SKU),
    CONSTRAINT CK_PRODUTO_PRECO CHECK (PRECO >= 0),
    CONSTRAINT CK_PRODUTO_ATIVO CHECK (ATIVO IN (0,1))
);
